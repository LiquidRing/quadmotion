/** Draw a string at (x, y); lowercase is drawn as caps. Returns the width. */
export function drawText(raster, str, x, y, color, scale = 2) {
  let cx = x;
  for (const ch of str) {
    const g = FONT5[ch.toUpperCase()] ?? FONT5[" "];
    g.forEach((row, j) => [...row].forEach((c, i) => c === "#" && raster.fill(cx + i * scale, y + j * scale, scale, scale, color)));
    cx += 6 * scale;
  }
  return cx - x;
}

export const textWidth = (str, scale = 2) => [...str].length * 6 * scale - scale;
