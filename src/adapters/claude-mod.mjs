// Generates a Claude Code mod (plugin with a hooks module) that draws the
// mascot in the band above the prompt and reacts to session events.
//
// Mod API facts this template relies on (checked against the engine's own
// typings, not the research doc):
//  - the frame timer is started in `session.start` with `$.clock.every`;
//    timers made inside a dispatch would die with it;
//  - drawing is a `ui.render` hook on { component: 'AbovePrompt' } that reads
//    an atom; writing the atom redraws the band (about 10/s, up to 30/s for an
//    expanded band in the terminal), so the mod ticks at 150 ms by default and only writes when the frame changes;
//  - an interrupted turn falls back to idle via e.props.isWorking;
//  - the hook yields (`next(e)`) when a survey holds the band or the band has
//    fewer rows/columns than the sprite, so it never forces scrolling.

import { frameToSpans } from "../core/pipeline.mjs";

const kebab = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/**
 * @returns {Record<string,string>} relative path -> file content
 * opts: { modName?, tickMs?, passes?, reducedMotion? }
 */
export function generateClaudeMod(compiled, opts = {}) {
  const { rig } = compiled;
  const modName = kebab(opts.modName ?? `${rig.name}-mascot`);
  const tickMs = opts.tickMs ?? 150;
  const passes = opts.passes ?? 2;

  // Deduplicate frames; encode spans compactly as [text, fg?, bg?].
  const frames = [];
  const index = new Map();
  const frameId = (frame) => {
    const rows = frameToSpans(frame, rig.palette).map((spans) => spans.map((s) => (s.bg ? [s.text, s.fg ?? "", s.bg] : s.fg ? [s.text, s.fg] : [s.text])));
    const key = JSON.stringify(rows);
    if (!index.has(key)) {
      index.set(key, frames.length);
      frames.push(rows);
    }
    return index.get(key);
  };
  const reducedFrame = frameId(compiled.poses[rig.reducedMotionPose]);
  const timelines = {};
  for (const [name, tl] of Object.entries(compiled.timelines)) {
    const seq = [];
    for (const f of tl.frames) {
      const id = frameId(f.frame);
      const ticks = Math.max(1, Math.round(f.durationMs / tickMs));
      for (let i = 0; i < ticks; i++) seq.push(id);
    }
    timelines[name] = { loop: tl.loop, seq };
  }
  const ev = rig.events ?? {};
  const idle = ev.idle && timelines[ev.idle] ? ev.idle : rig.defaultTimeline;
  const events = {
    start: ev["session.start"] && timelines[ev["session.start"]] ? ev["session.start"] : idle,
    idle,
    tool: ev["tool.call"] && timelines[ev["tool.call"]] ? ev["tool.call"] : null,
    done: ev["turn.complete"] && timelines[ev["turn.complete"]] ? ev["turn.complete"] : null,
  };

  const register = `// Generated by QuadMotion from rig "${rig.name}". Edit the rig and recompile
// instead of editing the frame data below.
import { atom, read, update } from 'claude-code'
import type { Register } from 'claude-code'

const ROWS = ${rig.rows}
const COLS = ${rig.cols}
const TICK_MS = ${tickMs}
/** Looping event scenes (tool, done) play this many passes, then idle resumes. */
const PASSES = ${passes}
/** Set true to draw the still pose only (prefers-reduced-motion). */
const REDUCED_MOTION = ${opts.reducedMotion ? "true" : "false"}

/** Rows of spans: [text, fg?, bg?] with hex colors. */
type Span = readonly [string, string?, string?]
const FRAMES: readonly (readonly (readonly Span[])[])[] = ${JSON.stringify(frames)}
const TIMELINES: Record<string, { loop: boolean; seq: readonly number[] }> = ${JSON.stringify(timelines)}
const EVENTS = ${JSON.stringify(events)} as const
const STILL = ${reducedFrame}

const frameAtom = atom({ plugin: '${modName}', key: 'frame' } as const, STILL)

export const register: Register = on => {
  let scene: string = EVENTS.start
  let tick = 0
  let shown = -1

  const play = (name: string | null) => {
    if (name && TIMELINES[name] && scene !== name) {
      scene = name
      tick = 0
    }
  }

  const frameNow = (): number => {
    const tl = TIMELINES[scene]
    if (!tl) return STILL
    const persistent = scene === EVENTS.idle || scene === EVENTS.tool
    const limit = tl.loop ? (persistent ? Infinity : tl.seq.length * PASSES) : tl.seq.length
    if (tick >= limit) {
      scene = EVENTS.idle
      tick = 0
      return TIMELINES[scene]?.seq[0] ?? STILL
    }
    return tl.seq[tick % tl.seq.length] ?? STILL
  }

  on('session.start', async ($, e, next) => {
    if (!REDUCED_MOTION) {
      // Timers must live outside a single dispatch: start them here.
      $.clock.every(TICK_MS, () => {
        tick += 1
        const f = frameNow()
        if (f !== shown) {
          shown = f
          void update($, frameAtom, () => f)
        }
      })
    }
    return next(e)
  })

  on('tool.call', ($, e, next) => {
    play(EVENTS.tool)
    return next(e)
  })

  on('turn.complete', ($, e, next) => {
    scene = EVENTS.idle
    play(EVENTS.done)
    return next(e)
  })

  on('ui.render', { component: 'AbovePrompt' }, async ($, e, next) => {
    if (e.props.hasSurvey || e.props.maxRows < ROWS || e.props.bodyColumns < COLS) {
      return next(e)
    }
    // An interrupted turn may never reach turn.complete: leave the working
    // scene once the band reports that no turn is running.
    if (!e.props.isWorking && scene === EVENTS.tool) play(EVENTS.idle)
    const { Box, Text } = $.ui.resolve(e)
    const f = REDUCED_MOTION ? STILL : await read($, frameAtom)
    const rows = FRAMES[f] ?? FRAMES[STILL] ?? []
    return (
      <Box flexDirection="column">
        {rows.map(row => (
          <Text wrap="truncate">
            {row.map(([text, fg, bg]) => (
              <Text color={fg || undefined} backgroundColor={bg}>
                {text}
              </Text>
            ))}
          </Text>
        ))}
      </Box>
    )
  })
}
`;

  const types = `/** Index into FRAMES of the frame the band draws. */
export type FrameIndex = number

declare module 'claude-code' {
  interface PluginState {
    '${modName}': { frame: FrameIndex }
  }
}
`;

  return {
    ".claude-plugin/plugin.json": `${JSON.stringify(
      { name: modName, version: "0.1.0", description: `Animated ${rig.name} mascot above the prompt (QuadMotion).`, author: { name: opts.author ?? "QuadMotion" }, types: "./types/index.d.ts" },
      null,
      2,
    )}\n`,
    "hooks/hooks.json": `${JSON.stringify({ modules: ["./register.tsx"] }, null, 2)}\n`,
    "hooks/register.tsx": register,
    "types/index.d.ts": types,
    "tests/mascot.test.tsx": modTest({ modName, rig, frames, timelines, events, reducedFrame, tickMs }),
  };
}

/** Behaviour test for `claude plugin test <mod>`: clock-driven frames, events, band yielding. */
function modTest({ modName, rig, frames, timelines, events, reducedFrame, tickMs }) {
  const text = (id) => frames[id].map((row) => row.map((s) => s[0]).join(""));
  const startSeq = timelines[events.start].seq;
  // The timer bumps the tick before drawing: after n ticks the band shows seq[n].
  const firstChange = startSeq.findIndex((id, t) => t >= 1 && id !== reducedFrame);
  const toolSeq = events.tool ? timelines[events.tool].seq : null;
  const toolFrame = toolSeq ? toolSeq[1 % toolSeq.length] : null;
  return `// Generated by QuadMotion. Run: claude plugin test <this mod folder>
import { expect, mock, test } from 'claude-code/testing'

const band = (maxRows: number, bodyColumns = 80) =>
  ({
    plugin: '${modName}',
    component: 'AbovePrompt',
    requestId: 'band',
    surface: 'terminal',
    props: {
      hasSurvey: false,
      isCollapsed: false,
      isWorking: false,
      maxRows,
      bodyColumns,
      scroll: { offset: 0, bodyRows: Math.max(1, maxRows - 1) },
      view: {},
    },
  }) as const

const STILL = ${JSON.stringify(text(reducedFrame))}
const START_STEP = ${JSON.stringify(firstChange >= 0 ? { tick: firstChange, rows: text(startSeq[firstChange]) } : null)}
const TOOL = ${JSON.stringify(toolFrame === null ? null : text(toolFrame))}

const rowsOf = async (ui: { findAll: (q: { type: string }) => Promise<{ text?: string }[]> }) =>
  (await ui.findAll({ type: 'Text' })).map(t => t.text ?? '').filter(t => t.length === ${rig.cols})

test('draws the still pose, then animates on the mod clock', async ($, on) => {
  const clock = mock.clock(on)
  on('session.start', (_, e) => ({ cwd: e.cwd }))
  await $.session.start({ cwd: '/', surface: 'terminal', isInteractive: true })

  const ui = await $.ui.mount(band(10))
  expect((await rowsOf(ui)).slice(0, ${rig.rows})).toEqual(STILL)

  if (START_STEP) {
    await clock.advance(${tickMs} * START_STEP.tick)
    expect((await rowsOf(ui)).slice(0, ${rig.rows})).toEqual(START_STEP.rows)
  }
  await ui.unmount()
})

test('a tool call switches to the working scene', async ($, on) => {
  const clock = mock.clock(on)
  on('session.start', (_, e) => ({ cwd: e.cwd }))
  on('tool.call', () => ({ result: {} }))
  await $.session.start({ cwd: '/', surface: 'terminal', isInteractive: true })
  if (!TOOL) return
  await $.tool.call({ tool: 'Bash', command: 'ls' })
  await clock.advance(${tickMs})
  const ui = await $.ui.mount(band(10))
  expect((await rowsOf(ui)).slice(0, ${rig.rows})).toEqual(TOOL)
  await ui.unmount()
})

test('yields the band when it has fewer rows than the sprite', async ($, on) => {
  on('ui.render', ($, e) => {
    const { Text } = $.ui.resolve(e)
    return <Text>engine</Text>
  })
  const ui = await $.ui.mount(band(${rig.rows - 1}))
  expect((await ui.find({ type: 'Text' }))?.text).toBe('engine')
  await ui.unmount()
})
`;
}
