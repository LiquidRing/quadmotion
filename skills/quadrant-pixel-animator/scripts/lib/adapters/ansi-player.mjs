// Generates a self-contained, dependency-free Node script that plays a
// compiled rig in the terminal (diff renderer + DEC Mode 2026 + DECRQM probe).

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { toBundle } from "../core/pipeline.mjs";

const CORE = ["glyphs.mjs", "quad-engine.mjs", "caps.mjs", "player.mjs"];

function inlineModule(file) {
  const src = readFileSync(fileURLToPath(new URL(`../core/${file}`, import.meta.url)), "utf8");
  return src
    .replace(/^import[\s\S]*?from\s+["'][^"']+["'];?\s*$/gm, "")
    .replace(/^export\s+(?=(const|function|class|async)\b)/gm, "");
}

export function generateAnsiPlayer(compiled) {
  const bundle = toBundle(compiled);
  return `#!/usr/bin/env node
// Generated by QuadMotion — standalone terminal player for "${bundle.rig.name}".
// Usage: node ${bundle.rig.name}.player.mjs [timeline] [--loops N] [--list]
// Env: QUADMOTION_REDUCED_MOTION=1, QUADMOTION_SYNC_OUTPUT=0|1, QUADMOTION_TRUECOLOR=0|1,
//      QUADMOTION_FULL_REPAINT=1, QUADMOTION_BG_FILL=1, NO_COLOR=1
${CORE.map((f) => `// ---- ${f} ----\n${inlineModule(f)}`).join("\n")}
// ---- data ----
const BUNDLE = ${JSON.stringify(bundle)};

// ---- main ----
const args = process.argv.slice(2);
if (args.includes("--list")) {
  console.log(Object.keys(BUNDLE.timelines).join("\\n"));
  process.exit(0);
}
const loopsIdx = args.indexOf("--loops");
// Without a TTY (pipes, CI, agents) play one pass instead of looping forever.
const loops = loopsIdx >= 0 ? Number(args[loopsIdx + 1]) : process.stdout.isTTY ? Infinity : 1;
const timeline = args.find((a, i) => !a.startsWith("--") && args[i - 1] !== "--loops") ?? BUNDLE.rig.defaultTimeline;
const caps = await detectCapabilitiesAsync();
const player = new TerminalPlayer(BUNDLE, caps);
try {
  await player.play(timeline, { loops });
} finally {
  player.restore();
}
`;
}
