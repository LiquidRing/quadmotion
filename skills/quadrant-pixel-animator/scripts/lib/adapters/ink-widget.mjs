// React/Ink adapter: a fixed-height mascot component.
//
// createMascotComponent is self-contained (no imports): the generator inlines
// its source into a standalone module, and it can also be used directly:
//
//   import React from "react"; import * as ink from "ink";
//   const Pip = createMascotComponent(spansBundle, { React, ink });
//   <Pip timeline="idle" />
//
// spansBundle = { rows, cols, defaultTimeline, reducedMotionPose,
//                 poses: { name: Span[][] },
//                 timelines: { name: { loop, frames: [{ durationMs, rows: Span[][] }] } } }
// Span = { text, fg?: "#rrggbb", bg?: "#rrggbb" }

import { frameToSpans } from "../core/pipeline.mjs";

export function createMascotComponent(data, { React, ink }) {
  const { Box, Text } = ink;
  const h = React.createElement;

  function renderRows(rows) {
    return h(
      Box,
      { flexDirection: "column", height: data.rows, width: data.cols, flexShrink: 0 },
      rows.map((spans, r) =>
        h(
          Text,
          { key: r, wrap: "truncate" },
          spans.map((s, i) => h(Text, { key: i, color: s.fg, backgroundColor: s.bg }, s.text)),
        ),
      ),
    );
  }

  function Mascot({ timeline = data.defaultTimeline, playing = true, reducedMotion = false, loops = Infinity, onDone } = {}) {
    const tl = data.timelines[timeline];
    const [state, setState] = React.useState({ index: 0, pass: 0 });
    React.useEffect(() => setState({ index: 0, pass: 0 }), [timeline]);
    const still = reducedMotion || !playing || !tl;
    React.useEffect(() => {
      if (still) return undefined;
      const frame = tl.frames[state.index];
      const id = setTimeout(() => {
        const next = state.index + 1;
        if (next < tl.frames.length) return setState({ index: next, pass: state.pass });
        const pass = state.pass + 1;
        if (!tl.loop || pass >= loops) return onDone?.();
        setState({ index: 0, pass });
      }, frame.durationMs);
      return () => clearTimeout(id);
    }, [still, tl, state, loops, onDone]);
    if (reducedMotion || !tl) return renderRows(data.poses[data.reducedMotionPose]);
    return renderRows(tl.frames[Math.min(state.index, tl.frames.length - 1)].rows);
  }
  Mascot.displayName = "QuadMotionMascot";
  return Mascot;
}

/** Convert a compiled rig into the spans bundle createMascotComponent reads. */
export function toSpansBundle(compiled, opts = {}) {
  const { rig } = compiled;
  const conv = (frame) => frameToSpans(frame, rig.palette, opts);
  return {
    name: rig.name,
    rows: rig.rows,
    cols: rig.cols,
    defaultTimeline: rig.defaultTimeline,
    reducedMotionPose: rig.reducedMotionPose,
    events: rig.events,
    poses: Object.fromEntries(Object.entries(compiled.poses).map(([n, f]) => [n, conv(f)])),
    timelines: Object.fromEntries(
      Object.entries(compiled.timelines).map(([n, tl]) => [
        n,
        { loop: tl.loop, tickMs: tl.tickMs, frames: tl.frames.map((f) => ({ durationMs: f.durationMs, rows: conv(f.frame) })) },
      ]),
    ),
  };
}

const pascal = (s) => s.replace(/(^|[-_\s]+)(\w)/g, (_, __, c) => c.toUpperCase());

/** Standalone ES module exporting the component (peer deps: react, ink). */
export function generateInkModule(compiled, opts = {}) {
  const data = toSpansBundle(compiled, opts);
  const name = `${pascal(data.name)}Mascot`;
  return `// Generated by QuadMotion — Ink component for "${data.name}".
// Peer dependencies: react >= 18, ink >= 4.
// Usage: import ${name} from "./${name}.mjs"; render(<${name} timeline="idle" />)
import React from "react";
import * as ink from "ink";

${createMascotComponent.toString()}

export const DATA = ${JSON.stringify(data)};
export const ${name} = createMascotComponent(DATA, { React, ink });
export default ${name};
`;
}
